import { createRequire } from 'node:module'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const require = createRequire(import.meta.url)
const read = path => readFile(path, 'utf8')

/** Pinned in apps/android/package.json; bump both together after reviewing the mermaid release. */
const MERMAID_VERSION = '12.2.0'

const mermaidPackage = require.resolve('mermaid/package.json')
const { version } = JSON.parse(await read(mermaidPackage))
if (version !== MERMAID_VERSION) {
  throw new Error(`build-mermaid.mjs bundles mermaid ${MERMAID_VERSION} but resolved ${version}.`)
}

const [library, renderer] = await Promise.all([
  read(resolve(dirname(mermaidPackage), 'dist/mermaid.min.js')),
  read(resolve(import.meta.dirname, 'mermaid-renderer.js')),
])
if (!library.includes('globalThis["mermaid"]')) {
  throw new Error(`mermaid ${version} dist/mermaid.min.js no longer defines the global mermaid.`)
}

/** See build-pdf.mjs: keeps the inline scripts from ending early or opening an HTML comment. */
const inline = source => source.replaceAll('</script', '<\\/script').replaceAll('<!--', '<\\!--')

/**
 * Runs before mermaid. The page must not reach the network, and console output is dropped
 * because parser errors quote the diagram source into logcat. No popup or link may leave it.
 */
const boot = `
const silence = function () {}
for (const name of ['log','info','debug','warn','error','trace','table','dir','dirxml','group','groupCollapsed','groupEnd','assert','count','time','timeLog','timeEnd']) {
  console[name] = silence
}
window.open = function () { return null }
window.alert = silence
window.prompt = function () { return null }
window.confirm = function () { return false }
document.addEventListener('click', function (event) { event.preventDefault(); event.stopPropagation() }, true)
`

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=1024,initial-scale=1,maximum-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; worker-src 'none'; frame-src 'none'; object-src 'none'; media-src 'none'; base-uri 'none'; form-action 'none'">
<title>Mermaid</title>
<style>html,body{margin:0;width:1024px;background:transparent}#stage{position:absolute;left:-20000px;top:0;width:4096px}</style>
</head>
<body>
<div id="stage"></div>
<script>${boot}</script>
<script>${inline(library)}</script>
<script>${inline(renderer)}</script>
</body>
</html>`

const out = resolve(import.meta.dirname, '../src/generated/mermaid-html.ts')
await mkdir(dirname(out), { recursive: true })
await writeFile(out, `// Generated by scripts/build-mermaid.mjs from pinned mermaid@${version}.\nexport const mermaidHtml = ${JSON.stringify(html)}\n`)
