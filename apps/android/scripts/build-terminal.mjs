import { createRequire } from 'node:module'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
const require = createRequire(import.meta.url)
const read = path => readFile(path, 'utf8')
const js = await read(require.resolve('@xterm/xterm'))
const fit = await read(require.resolve('@xterm/addon-fit'))
const css = await read(resolve(dirname(require.resolve('@xterm/xterm')), '../css/xterm.css'))
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'"><style>${css}
html,body,#terminal{height:100%;width:100%;margin:0;overflow:hidden}body{background:#101418}</style></head><body><div id="terminal"></div><script>${js.replaceAll('</script', '<\\/script')}</script><script>${fit.replaceAll('</script', '<\\/script')}</script><script>
const send = value => window.ReactNativeWebView.postMessage(JSON.stringify(value));
const term = new Terminal({fontSize:14,scrollback:2000,screenReaderMode:true,convertEol:false,disableStdin:true,theme:{background:'#101418',foreground:'#e6edf3'},linkHandler:{activate:()=>{}}});
const fit = new FitAddon.FitAddon();term.loadAddon(fit);term.open(document.getElementById('terminal'));
term.onData(data=>send({type:'data',data}));
term.onResize(size=>send({type:'resize',...size}));
window.receive = message => {
 if(message.type==='write'){if(message.reset)term.reset();term.write(message.data,()=>send({type:'ack',id:message.id}));}
 if(message.type==='enabled')term.options.disableStdin=!message.value;
 if(message.type==='focus')term.focus();
};
new ResizeObserver(()=>fit.fit()).observe(document.getElementById('terminal'));
fit.fit();send({type:'ready',cols:term.cols,rows:term.rows});
</script></body></html>`
const out = resolve(import.meta.dirname, '../src/generated/terminal-html.ts')
await mkdir(dirname(out), { recursive: true })
await writeFile(out, `// Generated by scripts/build-terminal.mjs from pinned xterm packages.\nexport const terminalHtml = ${JSON.stringify(html)}\n`)
